import { test } from "node:test";
import assert from "node:assert/strict";
import type { CommandNode } from "./commandTree.js";
import { checkExamples, renderCommandReference, renderRemoteScriptReference } from "./referenceDoc.js";

const tree: CommandNode<void, string>[] = [
  {
    name: "zeta",
    summary: "last one",
    run: () => {},
  },
  {
    name: "mute",
    summary: "mute tracks (<id>@<version> & `<code>`)",
    description: "Toggles the mute state.",
    destructive: true,
    requires: ["bridge"],
    options: [{ name: "all", short: "a", summary: "every | any match" }],
    args: [{ name: "track", kind: "path", kinds: ["track"], variadic: true, summary: "the tracks" }],
    examples: [{ line: "mute /Kick", note: "mute one" }],
    run: () => {},
  },
  {
    name: "grp",
    summary: "group",
    children: [{ name: "sub", summary: "a sub", args: [{ name: "kind", kind: "enum", choices: ["a", "b"] }], run: () => {} }],
  },
];

test("renderCommandReference: deterministic, sorted, with usage, arguments, options, requirements and examples", () => {
  const text = renderCommandReference(tree);
  assert.equal(renderCommandReference([...tree].reverse()), text);
  assert.ok(text.indexOf("## `grp`") < text.indexOf("## `mute`"));
  assert.ok(text.indexOf("## `mute`") < text.indexOf("## `zeta`"));
  assert.match(text, /\*\*Usage:\*\* `mute \[--all\] <track>…`/);
  assert.match(text, /\| `<track>…` \| path \(track\) \| yes \| the tracks \|/);
  assert.match(text, /\| `-a, --all` \| every \\\| any match \|/);
  assert.match(text, /mute tracks \(&lt;id>@&lt;version> &amp; `<code>`\)/);
  assert.match(text, /Needs the Remote Script/);
  assert.match(text, /```\nmute \/Kick\n```\n\nmute one/);
  assert.match(text, /Removes or irreversibly changes something/);
  assert.match(text, /### `grp sub`/);
  assert.match(text, /one of `a`, `b`/);
  assert.ok(text.startsWith("<!-- Generated by"));
  assert.ok(text.endsWith("\n"));
});

test("checkExamples: every runnable command needs an example that parses to it", () => {
  const ok: CommandNode<void, string>[] = [
    { name: "mute", summary: "m", args: [{ name: "t", kind: "path", variadic: true }], examples: [{ line: "mute /Kick, /Snare" }], run: () => {} },
    { name: "g", summary: "g", children: [{ name: "s", summary: "s", examples: [{ line: "g s" }, { line: "mute --help" }], run: () => {} }] },
  ];
  assert.deepEqual(checkExamples(ok), []);
  const bad: CommandNode<void, string>[] = [
    { name: "a", summary: "a", run: () => {} },
    { name: "b", summary: "b", examples: [{ line: "b --nope" }], run: () => {} },
    { name: "c", summary: "c", examples: [{ line: "a" }], run: () => {} },
  ];
  const problems = checkExamples(bad).join("\n");
  assert.match(problems, /a: no example/);
  assert.match(problems, /b: example "b --nope" does not parse/);
  assert.match(problems, /c: example "a" runs "a", not this command/);
});

test("renderRemoteScriptReference: one row per operation, versions in the header", () => {
  const text = renderRemoteScriptReference(
    [
      { name: "hello", summary: "Reports versions.", changesLive: false },
      { name: "chain_set", summary: "Mutes <chains>.", params: "{ a | b }", changesLive: true },
    ],
    { script: "0.1.0", protocol: 1 },
  );
  assert.match(text, /Script version \*\*0\.1\.0\*\*, protocol \*\*v1\*\*/);
  assert.match(text, /\| `hello` \| Reports versions\. \| – \| no \|/);
  assert.match(text, /\| `chain_set` \| Mutes &lt;chains>\. \| `\{ a \\\| b \}` \| yes/);
});
